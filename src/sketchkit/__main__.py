"""python -m sketchkit <command>

  guide              how to draw good diagrams with sketchkit (written for agents and people)
  api                every public name with its signature, generated from the code
  check SCRIPT       lay out every diagram a script registers and report layout problems
                     (--strict: also fail on warnings; --gallery FILE: write an HTML page to look at)
  skill              print the Claude Code skill for drawing diagrams with sketchkit
                     (--install [DIR]: write it to DIR/sketch-diagrams/SKILL.md, default .claude/skills)
"""

from __future__ import annotations

import argparse
import inspect
import pathlib
import runpy
import sys
from collections.abc import Callable
from importlib import resources
from typing import cast

import sketchkit

from .publish import Doc, Rendered, gallery, report


def guide() -> str:
    """The agent guide shipped with the package."""
    return resources.files("sketchkit").joinpath("guide.md").read_text(encoding="utf-8")


SKILL_NAME = "sketch-diagrams"


def skill() -> str:
    """The Claude Code skill shipped with the package (SKILL.md)."""
    return resources.files("sketchkit").joinpath("skills", SKILL_NAME, "SKILL.md").read_text(encoding="utf-8")


def install_skill(skills_dir: pathlib.Path, force: bool = False) -> pathlib.Path:
    """Write the skill to skills_dir/sketch-diagrams/SKILL.md. Won't replace a different file unless `force`."""
    target = skills_dir / SKILL_NAME / "SKILL.md"
    text = skill()
    if target.exists() and target.read_text(encoding="utf-8") != text and not force:
        raise FileExistsError(f"{target} exists and differs from this version; pass --force to replace it")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    return target


def _first_line(obj: object) -> str:
    doc = inspect.getdoc(obj) or ""
    return doc.strip().split("\n\n")[0].replace("\n", " ")


def _sig(obj: Callable[..., object]) -> str:
    """A signature without `self`, quoted annotations or `-> None`."""
    fields: object = getattr(obj, "_fields", None)
    if isinstance(fields, tuple):
        return "(" + ", ".join(map(str, cast("tuple[object, ...]", fields))) + ")"
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return "(...)"

    def ann(a: object) -> str:
        return a if isinstance(a, str) else inspect.formatannotation(a)

    parts: list[str] = []
    star_done = False
    for p in sig.parameters.values():
        if p.name == "self":
            continue
        if p.kind is p.KEYWORD_ONLY and not star_done:
            parts.append("*")
        star_done = star_done or p.kind in (p.VAR_POSITIONAL, p.KEYWORD_ONLY)
        text = ("*" if p.kind is p.VAR_POSITIONAL else "**" if p.kind is p.VAR_KEYWORD else "") + p.name
        if p.annotation is not p.empty:
            text += f": {ann(p.annotation)}"
        if p.default is not p.empty:
            text += f" = {p.default!r}"
        parts.append(text)
    ret = sig.return_annotation
    tail = "" if ret is sig.empty or ret in ("None", None) else f" -> {ann(ret)}"
    return f"({', '.join(parts)}){tail}"


SECTIONS: dict[str, list[str]] = {
    "Diagram and output": ["Diagram", "Placed", "Issue"],
    "Leaves": ["Box", "Label", "Headline", "Note", "Step", "Cell", "Circle", "Dot", "Mark", "Spacer", "Free"],
    "Layout": ["Row", "Col", "Split", "Grid", "Overlay", "Pad", "Region", "Legend"],
    "Scales": ["Track", "At", "Lanes", "Msg", "Act", "Gap"],
    "Edges": ["Arrow", "Line", "Bracket", "Port"],
    "Ideas": ["flow", "stack", "timeline", "sequence", "compare", "table", "overlap", "steps", "hub"],
    "Publishing": ["Doc", "run", "gallery", "to_svg", "report"],
    "Low level": ["Canvas", "figure", "insert", "escape"],
}
NODE_METHODS = ["tone", "dashed", "fixed", "align", "link", "pad", "at"]
NODE_PROPS = ["rect", "top", "bottom", "left", "right", "center", "linked"]


def api() -> str:
    """A compact reference of the public API, read from the live objects."""
    out = [f"# sketchkit {_version()} API (generated by `python -m sketchkit api`)", ""]
    for title, names in SECTIONS.items():
        out.append(f"## {title}")
        for name in names:
            obj = getattr(sketchkit, name)
            sig = _sig(obj) if hasattr(obj, "_fields") else _sig(obj.__init__) if inspect.isclass(obj) else _sig(obj)
            out.append(f"{name}{sig}")
            if (line := _first_line(obj)) and not line.startswith(name + "("):
                out.append(f"    {line}")
            if name in ("Diagram", "Doc"):
                for meth in ("layout", "render", "svg", "check", "diagram", "build"):
                    if hasattr(obj, meth):
                        m = getattr(obj, meth)
                        out.append(f"    .{meth}{_sig(m)}")
        out.append("")
    out.append("## Every node has")
    for meth in NODE_METHODS:
        m = getattr(sketchkit.Node, meth)
        out.append(f"    .{meth}{_sig(m)}  {_first_line(m)}".rstrip())
    out.append(f"    properties: {', '.join('.' + p for p in NODE_PROPS)}")
    out.append("")
    out.append("## Option values")
    for alias in ("Style", "Theme", "ToneName", "ResolvedTone", "Align", "Justify", "TextAlign", "TrackSide",
                  "TickMark", "LabelSide", "BracketSide", "Route", "MarkKind"):
        out.append(f"{alias} = {_literal(getattr(sketchkit, alias))}")
    out.append(f"DEFAULT_MEANINGS = {dict(sketchkit.DEFAULT_MEANINGS)}")
    return "\n".join(out) + "\n"


def _literal(alias: object) -> str:
    from typing import get_args

    vals: list[str] = []

    def walk(a: object) -> None:
        args = get_args(a)
        if not args:
            vals.append(repr(a))
        for x in args:
            if get_args(x):
                walk(x)
            else:
                vals.append(repr(x))

    walk(getattr(alias, "__value__", alias))
    return " | ".join(dict.fromkeys(vals))


def _version() -> str:
    from importlib.metadata import PackageNotFoundError, version

    try:
        return version("sketchkit")
    except PackageNotFoundError:
        return "dev"


def check(script: pathlib.Path, strict: bool, gallery_path: pathlib.Path | None) -> int:
    """Run a diagrams script without its __main__ block and check every Doc it defines."""
    sys.path.insert(0, str(script.resolve().parent))
    ns = runpy.run_path(str(script), run_name="__sketchkit_check__")
    docs = [v for v in ns.values() if isinstance(v, Doc)]
    if not docs:
        print(f"{script}: no Doc found (define one at module level: doc = Doc('post.md'))")
        return 2
    errors = warnings = 0
    rendered: list[Rendered] = []
    for doc in docs:
        issues = doc.check()
        errors += report(issues, doc.path.name)
        warnings += sum(i.level == "warn" for _, i in issues)
        if gallery_path:
            rendered += doc.render()
    if gallery_path:
        print("gallery:", gallery(rendered, gallery_path, title=f"check: {script.name}"))
    total = sum(len(d.diagrams) for d in docs)
    print(f"{total} diagram(s): {errors} error(s), {warnings} warning(s)")
    return 1 if errors or (strict and warnings) else 0


def main(argv: list[str] | None = None) -> int:
    reconfigure = getattr(sys.stdout, "reconfigure", None)
    if callable(reconfigure):
        reconfigure(encoding="utf-8")  # labels use ①, →, “ ” even on Windows consoles
    ap = argparse.ArgumentParser(prog="python -m sketchkit", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("guide", help="print the agent guide")
    sub.add_parser("api", help="print the generated API reference")
    c = sub.add_parser("check", help="check every diagram in a script")
    c.add_argument("script", type=pathlib.Path)
    c.add_argument("--strict", action="store_true", help="fail on warnings too")
    c.add_argument("--gallery", type=pathlib.Path, help="also write an HTML page with the diagrams")
    k = sub.add_parser("skill", help="print or install the Claude Code skill")
    k.add_argument("--install", nargs="?", const=pathlib.Path(".claude/skills"), type=pathlib.Path, metavar="DIR",
                   help="write it under DIR (default: .claude/skills in the current folder)")
    k.add_argument("--force", action="store_true", help="replace an installed copy that differs")
    a = ap.parse_args(argv)
    if a.cmd == "guide":
        print(guide(), end="")
        return 0
    if a.cmd == "api":
        print(api(), end="")
        return 0
    if a.cmd == "skill":
        if a.install is None:
            print(skill(), end="")
            return 0
        try:
            print("installed:", install_skill(a.install, a.force))
        except FileExistsError as e:
            print(e)
            return 1
        return 0
    return check(a.script, a.strict, a.gallery)


if __name__ == "__main__":
    sys.exit(main())
