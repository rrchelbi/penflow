"""`python -m penflow api`: a compact reference of the public API, generated from the live objects."""

from __future__ import annotations

import inspect
from collections.abc import Callable
from importlib.metadata import PackageNotFoundError, version
from typing import cast, get_args

import penflow

SECTIONS: dict[str, list[str]] = {
    "Diagram and output": ["Diagram", "Placed", "Issue"],
    "Leaves": ["Box", "Label", "Headline", "Note", "Step", "Cell", "Circle", "Dot", "Mark", "Spacer", "Free"],
    "Layout": ["Row", "Col", "Split", "Grid", "Overlay", "Pad", "Region", "Legend"],
    "Scales": ["Track", "At", "Lanes", "Msg", "Act", "Gap"],
    "Edges": ["Arrow", "Line", "Bracket", "Port"],
    "Ideas": ["flow", "stack", "timeline", "sequence", "compare", "table", "overlap", "steps", "hub"],
    "Publishing": ["Doc", "run", "gallery", "to_svg", "report"],
    "Penflow fences (docs/language.md)": ["SketchDoc", "parse_sketch", "Sketch", "SketchError", "convert_mermaid",
                                    "Converted"],
    "Low level": ["Canvas", "figure", "insert", "escape"],
}
NODE_METHODS = ["tone", "dashed", "fixed", "align", "link", "pad", "at"]
NODE_PROPS = ["rect", "top", "bottom", "left", "right", "center", "linked"]
OPTION_TYPES = ["Style", "Theme", "ToneName", "ResolvedTone", "Align", "Justify", "TextAlign", "TrackSide",
                "TickMark", "LabelSide", "BracketSide", "Route", "MarkKind"]


def api() -> str:
    """Every public name with its signature and the first line of its docstring."""
    out = [f"# penflow {_version()} API (generated by `python -m penflow api`)", ""]
    for title, names in SECTIONS.items():
        out.append(f"## {title}")
        for name in names:
            obj = getattr(penflow, name)
            sig = _sig(obj) if hasattr(obj, "_fields") else _sig(obj.__init__) if inspect.isclass(obj) else _sig(obj)
            out.append(f"{name}{sig}")
            if (line := _first_line(obj)) and not line.startswith(name + "("):
                out.append(f"    {line}")
            if name in ("Diagram", "Doc"):
                out += [f"    .{meth}{_sig(getattr(obj, meth))}"
                        for meth in ("layout", "render", "svg", "check", "diagram", "build") if hasattr(obj, meth)]
        out.append("")
    out.append("## Every node has")
    for meth in NODE_METHODS:
        m = getattr(penflow.Node, meth)
        out.append(f"    .{meth}{_sig(m)}  {_first_line(m)}".rstrip())
    out += [f"    properties: {', '.join('.' + p for p in NODE_PROPS)}", "", "## Option values"]
    out += [f"{alias} = {_literal(getattr(penflow, alias))}" for alias in OPTION_TYPES]
    out.append(f"DEFAULT_MEANINGS = {dict(penflow.DEFAULT_MEANINGS)}")
    return "\n".join(out) + "\n"


def _first_line(obj: object) -> str:
    doc = inspect.getdoc(obj) or ""
    return doc.strip().split("\n\n")[0].replace("\n", " ")


def _sig(obj: Callable[..., object]) -> str:
    """A signature without `self`, quoted annotations or `-> None`."""
    fields: object = getattr(obj, "_fields", None)
    if isinstance(fields, tuple):
        return "(" + ", ".join(map(str, cast("tuple[object, ...]", fields))) + ")"
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return "(...)"

    def ann(a: object) -> str:
        return a if isinstance(a, str) else inspect.formatannotation(a)

    parts: list[str] = []
    star_done = False
    for p in sig.parameters.values():
        if p.name == "self":
            continue
        if p.kind is p.KEYWORD_ONLY and not star_done:
            parts.append("*")
        star_done = star_done or p.kind in (p.VAR_POSITIONAL, p.KEYWORD_ONLY)
        text = ("*" if p.kind is p.VAR_POSITIONAL else "**" if p.kind is p.VAR_KEYWORD else "") + p.name
        if p.annotation is not p.empty:
            text += f": {ann(p.annotation)}"
        if p.default is not p.empty:
            text += f" = {p.default!r}"
        parts.append(text)
    ret = sig.return_annotation
    tail = "" if ret is sig.empty or ret in ("None", None) else f" -> {ann(ret)}"
    return f"({', '.join(parts)}){tail}"


def _literal(alias: object) -> str:
    """The values of a Literal alias, flattened: 'start' | 'center' | 'end'."""
    vals: list[str] = []

    def walk(a: object) -> None:
        args = get_args(a)
        if not args:
            vals.append(repr(a))
        for x in args:
            if get_args(x):
                walk(x)
            else:
                vals.append(repr(x))

    walk(getattr(alias, "__value__", alias))
    return " | ".join(dict.fromkeys(vals))


def _version() -> str:
    try:
        return version("penflow")
    except PackageNotFoundError:
        return "dev"
